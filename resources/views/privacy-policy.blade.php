<h1>Политика конфиденциальности и обработки персональных данных</h1>
<p><em>Дата последнего обновления: 16.09.2026</em></p>

<h2>1. Общие положения</h2>
<p>Настоящая Политика конфиденциальности (далее — «Политика») действует в отношении всей информации, которую Администратор Телеграм-бота (далее — «Бот») может получить о Пользователе во время использования им Бота.</p>
<p>Использование Бота означает безоговорочное согласие Пользователя с настоящей Политикой и указанными в ней условиями обработки его персональных данных. В случае несогласия с условиями Пользователь должен воздержаться от использования Бота.</p>
<p>Политика разработана в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных данных»[citation:7].</p>

<h2>2. Основные понятия</h2>
<ul>
    <li><strong>Персональные данные</strong> — любая информация, относящаяся к прямо или косвенно определенному физическому лицу (субъекту персональных данных)[citation:3].</li>
    <li><strong>Обработка персональных данных</strong> — любое действие (операция) с персональными данными, включая сбор, запись, систематизацию, накопление, хранение, уточнение, использование, передачу, обезличивание, блокирование, удаление, уничтожение[citation:3].</li>
    <li><strong>Оператор</strong> — Администратор Бота, самостоятельно организующий и осуществляющий обработку персональных данных.</li>
</ul>

<h2>3. Какие данные собираются</h2>
<p>В процессе использования Бота могут обрабатываться следующие персональные данные Пользователя:</p>
<ul>
    <li>Имя, фамилия (если указаны в профиле Telegram);</li>
    <li>Имя пользователя (username) в Telegram;</li>
    <li>Идентификатор пользователя (Telegram ID);</li>
    <li>Номер телефона;</li>
    <li>Адрес электронной почты (e-mail);</li>
    <li>Дата рождения, пол (при добровольном указании);</li>
    <li>Иные данные, которые Пользователь добровольно предоставляет через Бота.</li>
</ul>

<h2>4. Цели обработки персональных данных</h2>
<p>Персональные данные обрабатываются исключительно в следующих целях:</p>
<ul>
    <li>Идентификация Пользователя для предоставления доступа к функциям Бота;</li>
    <li>Регистрация Пользователя и создание учетной записи;</li>
    <li>Обеспечение функционирования и работы Бота;</li>
    <li>Обратная связь с Пользователем, включая направление уведомлений и ответов на запросы;</li>
    <li>Улучшение качества работы Бота и анализ статистики использования.</li>
</ul>

<h2>5. Правовые основания обработки</h2>
<p>Обработка персональных данных осуществляется на основании:</p>
<ul>
    <li>Согласия Пользователя, выраженного путем нажатия кнопки «Соглашаюсь» / «Отправить» при регистрации в Боте[citation:4];</li>
    <li>Исполнения договора, стороной которого является Пользователь.</li>
</ul>

<h2>6. Порядок и условия обработки</h2>
<p>Обработка персональных данных осуществляется с использованием средств автоматизации и без них.</p>
<p>Оператор принимает необходимые организационные и технические меры для защиты персональных данных от неправомерного или случайного доступа, уничтожения, изменения, блокирования, копирования, распространения.</p>
<p>Конфиденциальность персональных данных соблюдается, за исключением случаев, когда данные являются общедоступными или их раскрытие требуется в соответствии с законодательством РФ.</p>

<h2>7. Права субъекта персональных данных</h2>
<p>Пользователь имеет право:</p>
<ul>
    <li>Получать информацию, касающуюся обработки его персональных данных;</li>
    <li>Требовать уточнения, блокирования или уничтожения персональных данных, если они являются неполными, устаревшими, неточными или незаконно полученными[citation:9];</li>
    <li>Отозвать согласие на обработку персональных данных;</li>
    <li>Обжаловать действия Оператора в уполномоченный орган по защите прав субъектов персональных данных или в судебном порядке.</li>
</ul>

<h2>8. Сроки обработки</h2>
<p>Персональные данные обрабатываются до достижения целей обработки либо до отзыва согласия Пользователем. После достижения целей или отзыва согласия данные подлежат уничтожению или обезличиванию в срок, не превышающий 30 дней.</p>

<h2>9. Заключительные положения</h2>
<p>Оператор вправе вносить изменения в настоящую Политику. Новая редакция вступает в силу с момента ее размещения в Боте.</p>
<p>По всем вопросам, связанным с обработкой персональных данных, Пользователь может обратиться к Администратору Бота через Telegram.</p>
